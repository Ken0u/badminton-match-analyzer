import { spawnSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const python =
  process.env.FRONTEND_CONTRACT_PYTHON ??
  fileURLToPath(
    new URL(
      process.platform === "win32"
        ? "../../../.venv/Scripts/python.exe"
        : "../../../.venv/bin/python",
      import.meta.url,
    ),
  );
const result = spawnSync(
  python,
  [fileURLToPath(new URL("./export_openapi.py", import.meta.url))],
  {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 16 * 1024 * 1024,
  },
);
if (result.error || result.status !== 0) {
  throw new Error(
    `Backend schema export failed. Set FRONTEND_CONTRACT_PYTHON to the locked review interpreter.\n${result.error ?? result.stderr}`,
  );
}
const document = JSON.parse(result.stdout);
const types =
  "// Generated by npm run frontend:contract:generate. Do not edit.\n" +
  astToString(
    await openapiTS(document, { alphabetize: true, defaultNonNullable: false }),
  );
const outputs = [
  [
    "../src/api/generated/openapi.json",
    JSON.stringify(document, null, 2) + "\n",
  ],
  ["../src/api/generated/schema.ts", types],
];
for (const [path, expected] of outputs) {
  const url = new URL(path, import.meta.url);
  if (process.argv.includes("--write")) await writeFile(url, expected, "utf8");
  else if ((await readFile(url, "utf8")) !== expected)
    throw new Error(
      `Contract drift in ${fileURLToPath(url)}. Regenerate and review the actual backend changes.`,
    );
}
console.log(
  process.argv.includes("--write")
    ? "Generated backend OpenAPI contract."
    : "Backend OpenAPI contract matches generated files.",
);
