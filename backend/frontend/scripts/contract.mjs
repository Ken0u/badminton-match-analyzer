import { spawnSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const python =
  process.env.FRONTEND_CONTRACT_PYTHON ??
  fileURLToPath(
    new URL(
      process.platform === "win32"
        ? "../../../.venv/Scripts/python.exe"
        : "../../../.venv/bin/python",
      import.meta.url,
    ),
  );
// Keep exporter code here so this build workspace adds no Python namespace
// package to current distributions before the separately scoped delivery phase.
const exporter = String.raw`"""Export the actual application schema without touching an existing catalog."""

import json
import os
import sys
import tempfile
from pathlib import Path


def main():
    root = Path(sys.argv[1]).resolve()
    with tempfile.TemporaryDirectory(prefix="badminton-openapi-") as temporary:
        temporary_root = Path(temporary).resolve()
        data = temporary_root / "processed"
        # Configuration has import-time defaults. Pin these before any backend import.
        os.environ["BADMINTON_ROOT"] = str(root)
        os.environ["BADMINTON_DATA_DIR"] = str(data)
        os.environ["BADMINTON_EXPORT_DIR"] = str(temporary_root / "exports")
        os.environ.pop("BADMINTON_USERNAME", None)
        os.environ.pop("BADMINTON_PASSWORD", None)
        sys.path.insert(0, str(root / "backend"))
        from badminton.api import create_app

        app = create_app(root=root, data=data)
        # No lifespan/startup, workers, HTTP listener or inference is started.
        sys.stdout.write(json.dumps(app.openapi(), sort_keys=True, indent=2) + "\n")


if __name__ == "__main__":
    main()
`;
const result = spawnSync(python, ["-c", exporter, root], {
  cwd: root,
  encoding: "utf8",
  maxBuffer: 16 * 1024 * 1024,
});
if (result.error || result.status !== 0) {
  throw new Error(
    `Backend schema export failed. Set FRONTEND_CONTRACT_PYTHON to the locked review interpreter.\n${result.error ?? result.stderr}`,
  );
}
const document = JSON.parse(result.stdout);
const types =
  "// Generated by npm run frontend:contract:generate. Do not edit.\n" +
  astToString(
    await openapiTS(document, { alphabetize: true, defaultNonNullable: false }),
  );
const outputs = [
  [
    "../src/api/generated/openapi.json",
    JSON.stringify(document, null, 2) + "\n",
  ],
  ["../src/api/generated/schema.ts", types],
];
for (const [path, expected] of outputs) {
  const url = new URL(path, import.meta.url);
  if (process.argv.includes("--write")) await writeFile(url, expected, "utf8");
  else if ((await readFile(url, "utf8")) !== expected)
    throw new Error(
      `Contract drift in ${fileURLToPath(url)}. Regenerate and review the actual backend changes.`,
    );
}
console.log(
  process.argv.includes("--write")
    ? "Generated backend OpenAPI contract."
    : "Backend OpenAPI contract matches generated files.",
);
